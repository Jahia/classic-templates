/** The host of an http(s) URL, lower case and without "www."; undefined for anything else. */
const hostOf = (href: string): string | undefined => {
  const match = /^https?:\/\/([^/?#:]+)/i.exec(href.trim());
  return match?.[1].toLowerCase().replace(/^www\./, "");
};

/**
 * The icon of the network `href` points to: its host, or a subdomain of it (m.facebook.com).
 * Undefined for any other address, which then shows as text. Plain string work: server views run
 * in GraalJS, which has no URL parsing to rely on.
 */
export const socialIconOf = (href: string | undefined): SocialIcon | undefined => {
  const host = href ? hostOf(href) : undefined;
  if (!host) return undefined;
  const icon = ICONS.find((i) => i.hosts.some((h) => host === h || host.endsWith(`.${h}`)));
  return icon && { id: icon.id, name: icon.name, path: icon.path };
};
